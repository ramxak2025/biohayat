import Link from "next/link";

/**
 * Ссылка в списке — без предзагрузки при появлении на экране.
 *
 * Применять там, где ссылок много и заранее неизвестно, какую откроют:
 * карточки товаров, плитки категорий, подборки, пункты меню каталога,
 * колонки футера. Подгрузка для них включается по наведению/касанию —
 * этим занимается PrefetchOnIntent в макете витрины.
 *
 * Для одиночных ссылок с высоким намерением (корзина, «Каталог» в шапке,
 * кабинет, кнопки героя) обычный <Link> лучше: их единицы, и предзагрузка
 * там окупается.
 *
 * Это серверный компонент — обёртка не добавляет ни байта клиентского кода.
 */
export function ListLink(props: React.ComponentProps<typeof Link>) {
  return <Link prefetch={false} {...props} />;
}
